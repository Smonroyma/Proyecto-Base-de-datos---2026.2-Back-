BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL
);

CREATE TABLE cliente_telefono (
    telefono VARCHAR(20) NOT NULL,
    cliente_id_cliente INTEGER NOT NULL,

    PRIMARY KEY (telefono, cliente_id_cliente),

    FOREIGN KEY (cliente_id_cliente)
        REFERENCES cliente(id_cliente)
        ON DELETE CASCADE
);

CREATE TABLE cliente_correo (
    correo VARCHAR(250) PRIMARY KEY,
    cliente_id_cliente INTEGER NOT NULL,

    FOREIGN KEY (cliente_id_cliente)
        REFERENCES cliente(id_cliente)
        ON DELETE CASCADE
);

CREATE TABLE staff (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(250) NOT NULL UNIQUE,
    contrasena VARCHAR(250) NOT NULL,
    rol VARCHAR(50) NOT NULL,
    dos_fac_hab BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,

    CHECK (rol IN ('ADMINISTRADOR', 'MESERO'))
);

CREATE TABLE administrador (
    id_usuario INTEGER PRIMARY KEY,

    FOREIGN KEY (id_usuario)
        REFERENCES staff(id_usuario)
        ON DELETE CASCADE
);

CREATE TABLE mesero (
    id_usuario INTEGER PRIMARY KEY,
    estado VARCHAR(8) NOT NULL DEFAULT 'ACTIVO',

    FOREIGN KEY (id_usuario)
        REFERENCES staff(id_usuario)
        ON DELETE CASCADE,

    CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE mesa (
    num_mesa INTEGER PRIMARY KEY,
    capacidad INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',

    CHECK (num_mesa > 0),
    CHECK (capacidad > 0),
    CHECK (
        estado IN (
            'DISPONIBLE',
            'OCUPADA',
            'RESERVADA',
            'EN_MANTENIMIENTO'
        )
    )
);

CREATE TABLE categoria (
    nombre_categoria VARCHAR(100) PRIMARY KEY,
    descripcion VARCHAR(255) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',

    CHECK (estado IN ('ACTIVA', 'INACTIVA'))
);

CREATE TABLE producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(250) NOT NULL,
    precio NUMERIC(12,2) NOT NULL,
    disponibilidad BOOLEAN NOT NULL DEFAULT TRUE,
    categoria_nombre_categoria VARCHAR(100) NOT NULL,
    imagen_url VARCHAR(500) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,

    FOREIGN KEY (categoria_nombre_categoria)
        REFERENCES categoria(nombre_categoria),

    CHECK (precio > 0),
    CHECK (stock >= 0)
);

CREATE TABLE metodo_pago (
    tipo VARCHAR(30) PRIMARY KEY
);

CREATE TABLE reserva (
    id_reserva INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    num_personas INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADA',
    mesa_num_mesa INTEGER NOT NULL,
    cliente_id_cliente INTEGER NOT NULL,

    FOREIGN KEY (mesa_num_mesa)
        REFERENCES mesa(num_mesa),

    FOREIGN KEY (cliente_id_cliente)
        REFERENCES cliente(id_cliente),

    CHECK (num_personas > 0),

    CHECK (
        estado IN (
            'PENDIENTE',
            'CONFIRMADA',
            'CANCELADA',
            'COMPLETADA'
        )
    ),

    CONSTRAINT ex_reserva_sin_cruces
    EXCLUDE USING gist (
        mesa_num_mesa WITH =,
        tsrange(
            fecha + hora,
            fecha + hora + INTERVAL '3 hours',
            '[)'
        ) WITH &&
    )
    WHERE (estado <> 'CANCELADA')
);

CREATE TABLE pedido (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    observaciones VARCHAR(500),
    staff_id_usuario INTEGER NOT NULL,
    mesa_num_mesa INTEGER NOT NULL,
    cliente_id_cliente INTEGER NOT NULL,

    FOREIGN KEY (staff_id_usuario)
        REFERENCES staff(id_usuario),

    FOREIGN KEY (mesa_num_mesa)
        REFERENCES mesa(num_mesa),

    FOREIGN KEY (cliente_id_cliente)
        REFERENCES cliente(id_cliente),

    CHECK (
        estado IN (
            'PENDIENTE',
            'EN_PREPARACION',
            'ENTREGADO',
            'CANCELADO',
            'PAGADO'
        )
    )
);

CREATE TABLE detalle_pedido (
    cantidad INTEGER NOT NULL,
    precio NUMERIC(12,2) NOT NULL,
    pedido_id_pedido INTEGER NOT NULL,
    producto_id_producto INTEGER NOT NULL,

    PRIMARY KEY (pedido_id_pedido, producto_id_producto),

    FOREIGN KEY (pedido_id_pedido)
        REFERENCES pedido(id_pedido),

    FOREIGN KEY (producto_id_producto)
        REFERENCES producto(id_producto),

    CHECK (cantidad > 0),
    CHECK (precio > 0)
);

CREATE TABLE factura (
    num_factura VARCHAR(50) PRIMARY KEY,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'EMITIDA',
    total NUMERIC(12,2) NOT NULL,
    pedido_id_pedido INTEGER NOT NULL UNIQUE,
    impuesto NUMERIC(12,2) NOT NULL DEFAULT 0,
    propina NUMERIC(12,2) DEFAULT 0,

    FOREIGN KEY (pedido_id_pedido)
        REFERENCES pedido(id_pedido),

    CHECK (estado IN ('EMITIDA', 'ANULADA', 'PAGADA')),
    CHECK (total > 0),
    CHECK (impuesto >= 0),
    CHECK (propina >= 0)
);

CREATE TABLE pago (
    id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto NUMERIC(12,2) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'PAGADO',
    factura_num_factura VARCHAR(50) NOT NULL,
    metodo_pago_tipo VARCHAR(30) NOT NULL,

    FOREIGN KEY (factura_num_factura)
        REFERENCES factura(num_factura),

    FOREIGN KEY (metodo_pago_tipo)
        REFERENCES metodo_pago(tipo),

    CHECK (monto > 0),
    CHECK (estado IN ('PAGADO', 'REGISTRADO', 'ANULADO'))
);

CREATE FUNCTION validar_capacidad_reserva()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    capacidad_mesa INTEGER;
    estado_mesa VARCHAR(20);
BEGIN
    IF NEW.estado = 'CANCELADA' THEN
        RETURN NEW;
    END IF;

    SELECT capacidad, estado
    INTO capacidad_mesa, estado_mesa
    FROM mesa
    WHERE num_mesa = NEW.mesa_num_mesa
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La mesa indicada no existe';
    END IF;

    IF NEW.num_personas > capacidad_mesa THEN
        RAISE EXCEPTION
            'La reserva supera la capacidad de la mesa';
    END IF;

    IF estado_mesa = 'EN_MANTENIMIENTO' THEN
        RAISE EXCEPTION
            'No se puede reservar una mesa en mantenimiento';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_capacidad_reserva
BEFORE INSERT OR UPDATE ON reserva
FOR EACH ROW
EXECUTE FUNCTION validar_capacidad_reserva();

CREATE INDEX idx_cliente_telefono_cliente
    ON cliente_telefono(cliente_id_cliente);

CREATE INDEX idx_cliente_correo_cliente
    ON cliente_correo(cliente_id_cliente);

CREATE INDEX idx_producto_categoria
    ON producto(categoria_nombre_categoria);

CREATE INDEX idx_reserva_cliente
    ON reserva(cliente_id_cliente);

CREATE INDEX idx_pedido_staff
    ON pedido(staff_id_usuario);

CREATE INDEX idx_pedido_mesa
    ON pedido(mesa_num_mesa);

CREATE INDEX idx_pedido_cliente
    ON pedido(cliente_id_cliente);

CREATE INDEX idx_detalle_producto
    ON detalle_pedido(producto_id_producto);

CREATE INDEX idx_pago_factura
    ON pago(factura_num_factura);

CREATE INDEX idx_pago_metodo
    ON pago(metodo_pago_tipo);

CREATE VIEW vw_subtotal_pedido AS
SELECT
    p.id_pedido,
    COALESCE(
        SUM(d.cantidad * d.precio),
        0
    )::NUMERIC(12,2) AS subtotal
FROM pedido p
LEFT JOIN detalle_pedido d
    ON d.pedido_id_pedido = p.id_pedido
GROUP BY p.id_pedido;

CREATE VIEW vw_saldo_factura AS
SELECT
    f.num_factura,
    f.pedido_id_pedido,
    f.estado,
    f.total,
    COALESCE(
        SUM(pa.monto)
            FILTER (WHERE pa.estado IN ('PAGADO', 'REGISTRADO')),
        0
    )::NUMERIC(12,2) AS total_pagado,
    (
        f.total -
        COALESCE(
            SUM(pa.monto)
                FILTER (WHERE pa.estado IN ('PAGADO', 'REGISTRADO')),
            0
        )
    )::NUMERIC(12,2) AS saldo
FROM factura f
LEFT JOIN pago pa
    ON pa.factura_num_factura = f.num_factura
GROUP BY
    f.num_factura,
    f.pedido_id_pedido,
    f.estado,
    f.total;

COMMENT ON COLUMN detalle_pedido.precio
    IS 'Precio unitario histórico de la venta.';

COMMENT ON COLUMN staff.contrasena
    IS 'Hash de contraseña; no almacenar contraseñas en texto plano.';

COMMENT ON TABLE reserva
    IS 'Cada reserva no cancelada bloquea una mesa por tres horas.';

COMMIT;
